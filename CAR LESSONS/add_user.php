$allowed_roles = ['Admin', 'Officer', 'Clerk'];

if ($_SERVER['REQUEST_METHOD'] == 'POST') {
    $fullname = mysqli_real_escape_string($conn, $_POST['fullname']);
    $username = mysqli_real_escape_string($conn, $_POST['username']);
    $email = mysqli_real_escape_string($conn, $_POST['email']);
    $password = mysqli_real_escape_string($conn, $_POST['password']);
    $role = mysqli_real_escape_string($conn, $_POST['role']);
    $status = mysqli_real_escape_string($conn, $_POST['status']);

    if (!in_array($role, $allowed_roles, true)) {
        $message = "Only admin and staff accounts can be created here.";
        $message_type = 'danger';
    } else {
        // Check if username already exists
        $check_query = mysqli_query($conn, "SELECT * FROM users WHERE username = '$username'");
        if (mysqli_num_rows($check_query) > 0) {
            $message = "Username already exists!";
            $message_type = 'danger';
        } else {
            $hashedPassword = appPasswordHash($password);
            $insert_query = "INSERT INTO users (fullname, username, email, password, role, status) 
                             VALUES ('$fullname', '$username', '$email', '" . mysqli_real_escape_string($conn, $hashedPassword) . "', '$role', '$status')";
            if (mysqli_query($conn, $insert_query)) {
                $message = "User added successfully!";
                $message_type = 'success';
            } else {
                $message = "Error: " . mysqli_error($conn);
                $message_type = 'danger';
            }
        }
    }
}

